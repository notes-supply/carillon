/// How the stand-in CDN answers one file.
#[derive(Clone)]
pub(crate) enum Serve {
    Bytes(Vec<u8>),
    /// A body delimited by closing the connection, with no announced length.
    Unannounced(Vec<u8>),
    /// Announces one length and sends other bytes.
    Announce(u64, Vec<u8>),
    Status(u16),
    Redirect(String),
    /// Announces a length, sends a little, then nothing.
    Stall,
    /// Waits before answering normally.
    Slow(Duration, Vec<u8>),
    /// Streams this many generated bytes without holding them.
    Generated(u64),
}

#[derive(Default)]
pub(crate) struct CdnLog {
    pub(crate) requests: Vec<String>,
    pub(crate) with_authorization: usize,
}

/// A CDN stand-in answering `/attachments/<channel>/<id>/<name>` paths.
pub(crate) async fn serve_cdn(files: HashMap<String, Serve>) -> Result<(u16, Arc<Mutex<CdnLog>>)> {
    let listener = TcpListener::bind("127.0.0.1:0").await?;
    let port = listener.local_addr()?.port();
    let log = Arc::new(Mutex::new(CdnLog::default()));
    let recorded = log.clone();
    let files = Arc::new(files);
    tokio::spawn(async move {
        while let Ok((socket, _)) = listener.accept().await {
            let (log, files) = (recorded.clone(), files.clone());
            tokio::spawn(async move {
                let mut stream = BufReader::new(socket);
                let mut line = String::new();
                if stream.read_line(&mut line).await.is_err() {
                    return;
                }
                let path = line
                    .split_whitespace()
                    .nth(1)
                    .unwrap_or_default()
                    .to_owned();
                let mut authorized = false;
                loop {
                    let mut header = String::new();
                    if stream.read_line(&mut header).await.unwrap_or(0) == 0 || header == "\r\n" {
                        break;
                    }
                    authorized |= header.to_ascii_lowercase().starts_with("authorization:");
                }
                if let Ok(mut log) = log.lock() {
                    log.requests.push(path.clone());
                    log.with_authorization += usize::from(authorized);
                }
                let key = path.split('?').next().unwrap_or_default();
                let reply = match files.get(key).cloned() {
                    None => status(404),
                    Some(Serve::Bytes(bytes)) => ok(Some(bytes.len() as u64), &bytes),
                    Some(Serve::Unannounced(bytes)) => ok(None, &bytes),
                    Some(Serve::Announce(length, bytes)) => ok(Some(length), &bytes),
                    Some(Serve::Status(code)) => status(code),
                    Some(Serve::Redirect(target)) => format!(
                        "HTTP/1.1 302 Found\r\nLocation: {target}\r\nContent-Length: 0\r\nConnection: close\r\n\r\n"
                    )
                    .into_bytes(),
                    Some(Serve::Stall) => {
                        let _ = stream
                            .write_all(b"HTTP/1.1 200 OK\r\nContent-Length: 100\r\n\r\npartial")
                            .await;
                        tokio::time::sleep(Duration::from_secs(3600)).await;
                        return;
                    }
                    Some(Serve::Slow(delay, bytes)) => {
                        tokio::time::sleep(delay).await;
                        ok(Some(bytes.len() as u64), &bytes)
                    }
                    Some(Serve::Generated(length)) => {
                        let _ = stream.write_all(&ok(Some(length), &[])).await;
                        let block = vec![0x5a_u8; 256 * 1024];
                        let mut sent = 0;
                        while sent < length {
                            let chunk = usize::try_from((length - sent).min(block.len() as u64))
                                .unwrap_or(block.len());
                            if stream.write_all(&block[..chunk]).await.is_err() {
                                return;
                            }
                            sent += chunk as u64;
                        }
                        Vec::new()
                    }
                };
                let _ = stream.write_all(&reply).await;
                let _ = stream.shutdown().await;
            });
        }
    });
    Ok((port, log))
}

fn ok(length: Option<u64>, body: &[u8]) -> Vec<u8> {
    let mut reply = b"HTTP/1.1 200 OK\r\n".to_vec();
    if let Some(length) = length {
        reply.extend(format!("Content-Length: {length}\r\n").as_bytes());
    }
    reply.extend(b"Connection: close\r\n\r\n");
    reply.extend(body);
    reply
}

fn status(code: u16) -> Vec<u8> {
    format!("HTTP/1.1 {code} Status\r\nContent-Length: 0\r\nConnection: close\r\n\r\n").into_bytes()
}

/// A Discord API stand-in for message 500 in channel 300: its current
/// attachments, or a deletion when `None`.
pub(crate) async fn serve_discord(
    attachments: Option<Vec<Value>>,
) -> Result<(Arc<twilight_http::Client>, Arc<Mutex<usize>>)> {
    let lookups = Arc::new(Mutex::new(0));
    let counted = lookups.clone();
    let app = Router::new()
        .route(
            "/api/v10/channels/300/messages/500",
            axum::routing::get(move |State(attachments): State<Option<Vec<Value>>>| {
                let counted = counted.clone();
                async move {
                    if let Ok(mut lookups) = counted.lock() {
                        *lookups += 1;
                    }
                    match attachments {
                        Some(attachments) => Json(json!({
                            "id": "500", "channel_id": "300",
                            "author": {"id": "200", "username": "sender", "discriminator": "0"},
                            "content": "", "attachments": attachments, "embeds": [],
                            "mention_everyone": false, "mention_roles": [], "mentions": [],
                            "pinned": false, "timestamp": "2026-01-01T00:00:00.000000+00:00",
                            "tts": false, "type": 0
                        }))
                        .into_response(),
                        None => (
                            StatusCode::NOT_FOUND,
                            Json(json!({"message": "Unknown Message", "code": 10008})),
                        )
                            .into_response(),
                    }
                }
            }),
        )
        .with_state(attachments);
    let listener = TcpListener::bind("127.0.0.1:0").await?;
    let address = listener.local_addr()?;
    tokio::spawn(async move { axum::serve(listener, app).await });
    Ok((
        Arc::new(
            twilight_http::Client::builder()
                .token("test-only".to_owned())
                .proxy(address.to_string(), true)
                .ratelimiter(None)
                .build(),
        ),
        lookups,
    ))
}

pub(crate) fn attachment(port: u16, id: &str, name: &str, size: u64) -> SourceAttachment {
    SourceAttachment {
        id: id.to_owned(),
        filename: name.to_owned(),
        size,
        content_type: Some("application/octet-stream".to_owned()),
        url: format!("http://127.0.0.1:{port}/attachments/300/{id}/{name}?ex=1&is=2&hm=signed"),
    }
}

/// The stand-in Discord's description of an attachment.
pub(crate) fn described(port: u16, id: &str, name: &str, size: u64, path: &str) -> Value {
    json!({
        "id": id, "filename": name, "size": size,
        "url": format!("http://127.0.0.1:{port}{path}?ex=3&is=4&hm=fresh"),
        "proxy_url": format!("http://127.0.0.1:{port}{path}")
    })
}

fn plan(attachments: Vec<SourceAttachment>) -> MessagePlan {
    MessagePlan {
        message_id: "500".to_owned(),
        guild_id: "100".to_owned(),
        user_id: "200".to_owned(),
        agent_id: "default".to_owned(),
        channel_id: "300".to_owned(),
        route_channel_id: "300".to_owned(),
        content: String::new(),
        attachments,
        create_thread: false,
        adopt_thread: false,
        native: Value::Null,
    }
}

fn downloads(staging: &Path, port: u16, policy: AttachmentPolicy) -> Result<Downloads> {
    Ok(Downloads::open(staging.to_path_buf(), policy)?.with_fixture_cdn(port))
}

fn soon() -> Instant {
    Instant::now() + Duration::from_secs(30)
}

fn entries(directory: &Path) -> Result<usize> {
    Ok(std::fs::read_dir(directory)?.count())
}

async fn wait_until_empty(directory: &Path) -> Result<()> {
    for _ in 0..200 {
        if entries(directory)? == 0 {
            return Ok(());
        }
        tokio::time::sleep(Duration::from_millis(5)).await;
    }
    Err(anyhow!("staging was not removed"))
}

