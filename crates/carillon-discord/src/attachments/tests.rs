#[tokio::test]
async fn files_stream_to_generated_names_without_credentials_and_staging_is_released() -> Result<()>
{
    let first = vec![1_u8; 200_000];
    let (port, log) = serve_cdn(HashMap::from([
        (
            "/attachments/300/601/first.bin".to_owned(),
            Serve::Bytes(first.clone()),
        ),
        (
            "/attachments/300/602/second.txt".to_owned(),
            Serve::Unannounced(b"no length announced".to_vec()),
        ),
    ]))
    .await?;
    let (http, _) = serve_discord(None).await?;
    let staging = tempfile::tempdir()?;
    let downloads = downloads(staging.path(), port, AttachmentPolicy::default())?;
    let files = vec![
        attachment(port, "601", "first.bin", first.len() as u64),
        attachment(port, "602", "second.txt", 19),
    ];
    downloads
        .admit(&files)
        .map_err(|refusal| anyhow!(refusal.0))?;
    let staged = downloads
        .stage(Some(&http), &plan(files), soon())
        .await
        .map_err(|refusal| anyhow!(refusal.0))?;
    let directory = staging.path().join(&staged.manifest.batch);
    assert_eq!(std::fs::read(directory.join("0"))?, first);
    assert_eq!(std::fs::read(directory.join("1"))?, b"no length announced");
    assert_eq!(entries(&directory)?, 2);
    assert_eq!(
        std::fs::metadata(directory.join("0"))?.permissions().mode() & 0o777,
        0o600
    );
    assert_eq!(staged.manifest.files[0].name, "first.bin");
    assert_eq!(staged.manifest.files[1].size, 19);
    {
        let log = log.lock().map_err(|_| anyhow!("poisoned"))?;
        assert_eq!(log.requests.len(), 2);
        assert_eq!(log.with_authorization, 0);
    }
    assert_eq!(
        downloads.room.available_permits(),
        super::kib(2048 * 1024 * 1024) - 196
    );
    drop(staged);
    wait_until_empty(staging.path()).await?;
    for _ in 0..200 {
        if downloads.room.available_permits() == super::kib(2048 * 1024 * 1024) {
            return Ok(());
        }
        tokio::time::sleep(Duration::from_millis(5)).await;
    }
    Err(anyhow!("staging room was not released"))
}

#[tokio::test]
async fn policy_refuses_before_any_request() -> Result<()> {
    let (port, log) = serve_cdn(HashMap::new()).await?;
    let staging = tempfile::tempdir()?;
    let policy = AttachmentPolicy {
        max_files: 2,
        max_file_mib: 1,
        max_message_mib: 1,
        staging_mib: 1,
        ..AttachmentPolicy::default()
    };
    let downloads = downloads(staging.path(), port, policy)?;
    let mib = 1024 * 1024;
    let too_large = "Carillon accepts attachments of up to 1 MiB each and 1 MiB per message, so this message was not accepted.";
    for (files, refused) in [
        (
            vec![
                attachment(port, "601", "a", 1),
                attachment(port, "602", "b", 1),
                attachment(port, "603", "c", 1),
            ],
            "Carillon accepts at most 2 attachments per message, so this message was not accepted.",
        ),
        (vec![attachment(port, "601", "a", mib + 1)], too_large),
        (
            vec![
                attachment(port, "601", "a", mib / 2 + 1),
                attachment(port, "602", "b", mib / 2),
            ],
            too_large,
        ),
        (
            vec![SourceAttachment {
                url: "https://evil.test/attachments/300/601/a".to_owned(),
                ..attachment(port, "601", "a", 1)
            }],
            "`a` is not a Discord attachment Carillon can download, so this message was not accepted.",
        ),
    ] {
        assert_eq!(
            downloads
                .admit(&files)
                .err()
                .map(|refusal| refusal.0)
                .as_deref(),
            Some(refused)
        );
    }
    let disabled = Downloads::open(
        staging.path().join("other"),
        AttachmentPolicy {
            enabled: false,
            ..AttachmentPolicy::default()
        },
    )?;
    let refusal = disabled
        .admit(&[attachment(port, "601", "a", 1)])
        .err()
        .context("disabled attachments admitted")?;
    assert!(refusal.0.contains("not enabled"));
    assert!(
        log.lock()
            .map_err(|_| anyhow!("poisoned"))?
            .requests
            .is_empty()
    );
    Ok(())
}

#[tokio::test]
async fn bodies_must_match_the_announced_length_and_redirects_are_not_followed() -> Result<()> {
    let (port, log) = serve_cdn(HashMap::from([
        (
            "/attachments/300/601/long".to_owned(),
            Serve::Unannounced(vec![0; 64]),
        ),
        (
            "/attachments/300/602/lying".to_owned(),
            Serve::Announce(10, vec![0; 10]),
        ),
        (
            "/attachments/300/603/moved".to_owned(),
            Serve::Redirect("http://127.0.0.1:1/attachments/300/603/elsewhere".to_owned()),
        ),
        (
            "/attachments/300/604/short".to_owned(),
            Serve::Unannounced(vec![0; 4]),
        ),
    ]))
    .await?;
    let (http, _) = serve_discord(None).await?;
    let staging = tempfile::tempdir()?;
    let downloads = downloads(staging.path(), port, AttachmentPolicy::default())?;
    for (file, case) in [
        (
            attachment(port, "601", "long", 8),
            "more bytes than declared",
        ),
        (
            attachment(port, "602", "lying", 20),
            "announced length differs",
        ),
        (attachment(port, "603", "moved", 8), "redirect"),
        (
            attachment(port, "604", "short", 8),
            "fewer bytes than declared",
        ),
    ] {
        let refusal = downloads
            .stage(Some(&http), &plan(vec![file]), soon())
            .await
            .err()
            .with_context(|| format!("accepted {case}"))?;
        assert!(!refusal.0.contains("127.0.0.1"), "{}", refusal.0);
        assert!(!refusal.0.contains("hm="), "{}", refusal.0);
    }
    wait_until_empty(staging.path()).await?;
    let log = log.lock().map_err(|_| anyhow!("poisoned"))?;
    assert!(!log.requests.iter().any(|path| path.contains("elsewhere")));
    // A short body is worth retrying; the others are refused at once.
    assert_eq!(
        log.requests
            .iter()
            .filter(|path| path.starts_with("/attachments/300/604/"))
            .count(),
        super::ATTEMPTS as usize
    );
    Ok(())
}

