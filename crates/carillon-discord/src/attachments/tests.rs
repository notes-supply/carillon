#[tokio::test]
async fn an_expired_address_is_refreshed_once_from_the_same_message() -> Result<()> {
    let fresh = "/attachments/300/601/fresh.bin";
    let (port, log) = serve_cdn(HashMap::from([
        (
            "/attachments/300/601/stale.bin".to_owned(),
            Serve::Status(403),
        ),
        (fresh.to_owned(), Serve::Bytes(b"fresh bytes".to_vec())),
        (
            "/attachments/300/602/gone.bin".to_owned(),
            Serve::Status(404),
        ),
    ]))
    .await?;
    let staging = tempfile::tempdir()?;
    let downloads = downloads(staging.path(), port, AttachmentPolicy::default())?;
    let stale = attachment(port, "601", "stale.bin", 11);

    // The same attachment ID and size on the same message: downloaded.
    let (http, lookups) =
        serve_discord(Some(vec![described(port, "601", "stale.bin", 11, fresh)])).await?;
    let staged = downloads
        .stage(Some(&http), &plan(vec![stale.clone()]), soon())
        .await
        .map_err(|refusal| anyhow!(refusal.0))?;
    assert_eq!(
        std::fs::read(staging.path().join(&staged.manifest.batch).join("0"))?,
        b"fresh bytes"
    );
    assert_eq!(*lookups.lock().map_err(|_| anyhow!("poisoned"))?, 1);
    drop(staged);

    // Replaced (other size), removed, or a deleted message: refused, never
    // substituted. An address that is still stale after one refresh fails.
    for (attachments, case) in [
        (
            Some(vec![described(port, "601", "stale.bin", 12, fresh)]),
            "resized",
        ),
        (
            Some(vec![described(port, "609", "other.bin", 11, fresh)]),
            "replaced",
        ),
        (None, "deleted"),
        (
            Some(vec![described(
                port,
                "602",
                "gone.bin",
                11,
                "/attachments/300/602/gone.bin",
            )]),
            "still stale",
        ),
    ] {
        let (http, lookups) = serve_discord(attachments).await?;
        let file = if case == "still stale" {
            attachment(port, "602", "gone.bin", 11)
        } else {
            stale.clone()
        };
        let refusal = downloads
            .stage(Some(&http), &plan(vec![file]), soon())
            .await
            .err()
            .with_context(|| format!("{case} accepted"))?;
        assert!(
            refusal.0.contains("removed or replaced") || refusal.0.contains("no longer serves"),
            "{case}: {}",
            refusal.0
        );
        assert_eq!(
            *lookups.lock().map_err(|_| anyhow!("poisoned"))?,
            1,
            "{case}"
        );
    }
    assert!(
        log.lock()
            .map_err(|_| anyhow!("poisoned"))?
            .requests
            .iter()
            .all(|path| path.starts_with("/attachments/300/60"))
    );
    wait_until_empty(staging.path()).await?;
    Ok(())
}

